from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

from cas.modeling.threshold_policy import (
    build_threshold_policy_experiments,
    build_threshold_policy_report,
)

ROOT = Path(__file__).resolve().parents[1]
PREDICTION_SCORES_PATH = (
    ROOT / "data" / "outputs" / "dashboard" / "feature_46_mvp" / "prediction_scores.csv"
)
OUTPUT_DIR = ROOT / "data" / "outputs" / "modeling" / "feature_46_xgboost" / "diagnostics"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Export validation-selected threshold policy experiments for the "
            "46-feature XGBoost model."
        )
    )
    parser.add_argument(
        "--prediction-scores",
        type=Path,
        default=PREDICTION_SCORES_PATH,
        help="prediction_scores.csv generated by export_feature_46_dashboard_artifacts.py.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=OUTPUT_DIR,
        help="Directory where threshold policy artifacts will be written.",
    )
    return parser.parse_args()


def _read_prediction_scores(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(
            f"Prediction scores file not found: {path}. "
            "Run scripts/export_feature_46_dashboard_artifacts.py first."
        )
    frame = pd.read_csv(path, encoding="utf-8-sig")
    required_columns = {
        "split",
        "market",
        "corp_name",
        "fiscal_year",
        "industry_macro_category",
        "is_speculative",
        "prob_speculative",
    }
    missing_columns = sorted(required_columns - set(frame.columns))
    if missing_columns:
        raise KeyError(f"prediction_scores.csv is missing required columns: {missing_columns}")
    frame = frame.copy()
    frame["is_speculative"] = frame["is_speculative"].astype(int)
    frame["prob_speculative"] = pd.to_numeric(frame["prob_speculative"], errors="coerce")
    return frame


def write_outputs(
    output_dir: Path,
    metrics: pd.DataFrame,
    segment_thresholds: pd.DataFrame,
    focus_segment_metrics: pd.DataFrame,
    summary: dict[str, object],
) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    metrics.to_csv(
        output_dir / "threshold_policy_experiment_metrics.csv",
        index=False,
        encoding="utf-8-sig",
    )
    segment_thresholds.to_csv(
        output_dir / "threshold_policy_segment_thresholds.csv",
        index=False,
        encoding="utf-8-sig",
    )
    focus_segment_metrics.to_csv(
        output_dir / "threshold_policy_focus_segment_metrics.csv",
        index=False,
        encoding="utf-8-sig",
    )
    (output_dir / "threshold_policy_experiment_summary.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    (output_dir / "threshold_policy_experiment_report.md").write_text(
        build_threshold_policy_report(metrics, segment_thresholds, focus_segment_metrics, summary),
        encoding="utf-8",
    )


def main() -> None:
    args = parse_args()
    scores = _read_prediction_scores(args.prediction_scores)
    metrics, segment_thresholds, focus_segment_metrics, summary = (
        build_threshold_policy_experiments(scores)
    )
    write_outputs(args.output_dir, metrics, segment_thresholds, focus_segment_metrics, summary)
    print(f"Wrote threshold policy diagnostics to {args.output_dir}")


if __name__ == "__main__":
    main()
