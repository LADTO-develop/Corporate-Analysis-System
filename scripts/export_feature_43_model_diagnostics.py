def write_json(path: Path, payload: object) -> None:
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def main() -> None:
    args = parse_args()
    prediction_scores_path = args.prediction_scores.resolve()
    output_dir = args.output_dir.resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    scores = _read_prediction_scores(prediction_scores_path)
    threshold = _resolve_primary_threshold(scores, args.threshold)
    segment_performance = build_segment_performance(scores, threshold)
    threshold_sweep = build_threshold_sweep(scores, threshold)
    calibration_bins = build_calibration_bins(scores)
    error_cases = build_error_cases(
        scores,
        threshold,
        top_error_cases=args.top_error_cases,
    )
    summary = build_summary_payload(
        scores=scores,
        threshold=threshold,
        segment_performance=segment_performance,
        threshold_sweep=threshold_sweep,
        calibration_bins=calibration_bins,
        error_cases=error_cases,
        prediction_scores_path=prediction_scores_path,
    )
    markdown_report = build_markdown_report(
        summary=summary,
        segment_performance=segment_performance,
        threshold_sweep=threshold_sweep,
        calibration_bins=calibration_bins,
        error_cases=error_cases,
    )

    segment_performance.to_csv(
        output_dir / "segment_performance.csv",
        index=False,
        encoding="utf-8-sig",
    )
    threshold_sweep.to_csv(output_dir / "threshold_sweep.csv", index=False, encoding="utf-8-sig")
    calibration_bins.to_csv(
        output_dir / "calibration_bins.csv",
        index=False,
        encoding="utf-8-sig",
    )
    error_cases.to_csv(output_dir / "error_cases.csv", index=False, encoding="utf-8-sig")
    write_json(output_dir / "model_diagnostics_summary.json", summary)
    (output_dir / "model_diagnostics_report.md").write_text(markdown_report, encoding="utf-8")

    print(f"feature_43 model diagnostics written to: {output_dir}")


if __name__ == "__main__":
    main()
