def _safe_float(value: object) -> float | None:
    if value is None:
        return None
    try:
        numeric = float(value)
    except (TypeError, ValueError):
        return None
    if np.isnan(numeric):
        return None
    return numeric


def _round_or_none(value: object, digits: int = 4) -> float | None:
    numeric = _safe_float(value)
    if numeric is None:
        return None
    return round(numeric, digits)


def _read_prediction_scores(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(
            f"Prediction scores file not found: {path}. "
            "Run scripts/export_feature_43_dashboard_artifacts.py first."
        )
    frame = pd.read_csv(path, encoding="utf-8-sig")
    required_columns = {
        "split",
        "market",
        "stock_code",
        "corp_name",
        "fiscal_year",
        "industry_macro_category",
        "is_speculative",
        "prob_speculative",
    }
    missing_columns = sorted(required_columns - set(frame.columns))
    if missing_columns:
        raise KeyError(f"prediction_scores.csv is missing required columns: {missing_columns}")
    frame = frame.copy()
    frame["is_speculative"] = frame["is_speculative"].astype(int)
    frame["prob_speculative"] = pd.to_numeric(frame["prob_speculative"], errors="coerce")
    return frame


def _resolve_primary_threshold(scores: pd.DataFrame, override: float | None) -> float:
    if override is not None:
        return override
    threshold_column = scores.get("threshold")
    if threshold_column is None:
        return DEFAULT_THRESHOLD
    candidates = [
        numeric
        for numeric in (_safe_float(value) for value in threshold_column.dropna().unique())
        if numeric is not None
    ]
    if not candidates:
        return DEFAULT_THRESHOLD
    return float(candidates[0])


def _metrics_for_frame(frame: pd.DataFrame, threshold: float) -> dict[str, float | int | None]:
    from sklearn.metrics import (
        average_precision_score,
        log_loss,
        roc_auc_score,
    )

    y_true = frame["is_speculative"].astype(int)
    probabilities = pd.to_numeric(frame["prob_speculative"], errors="coerce")
    valid_mask = probabilities.notna()
    y_true = y_true.loc[valid_mask]
    probabilities = probabilities.loc[valid_mask]
    predictions = (probabilities >= threshold).astype(int)

    true_positive = int(((y_true == 1) & (predictions == 1)).sum())
    true_negative = int(((y_true == 0) & (predictions == 0)).sum())
    false_positive = int(((y_true == 0) & (predictions == 1)).sum())
    false_negative = int(((y_true == 1) & (predictions == 0)).sum())
    has_two_classes = y_true.nunique() == 2
    logloss_value: float | None = None
    if has_two_classes:
        clipped_probabilities = np.clip(probabilities.to_numpy(dtype=float), 1e-15, 1 - 1e-15)
        logloss_value = float(log_loss(y_true, clipped_probabilities))
    precision_denominator = true_positive + false_positive
    recall_denominator = true_positive + false_negative
    specificity_denominator = true_negative + false_positive
    precision = true_positive / precision_denominator if precision_denominator else 0.0
    recall = true_positive / recall_denominator if recall_denominator else 0.0
    specificity = true_negative / specificity_denominator if specificity_denominator else 0.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    accuracy = (true_positive + true_negative) / len(y_true) if len(y_true) else None
    balanced_accuracy = (recall + specificity) / 2 if has_two_classes else None

    return {
        "rows": len(y_true),
        "positive_rows": int(y_true.sum()),
        "positive_rate": float(y_true.mean()) if len(y_true) else None,
        "threshold": float(threshold),
        "pr_auc": float(average_precision_score(y_true, probabilities))
        if has_two_classes
        else None,
        "roc_auc": float(roc_auc_score(y_true, probabilities)) if has_two_classes else None,
        "logloss": logloss_value,
        "accuracy": accuracy,
        "balanced_accuracy": balanced_accuracy,
        "precision": precision,
        "recall": recall,
        "f1": f1,
        "true_negative": true_negative,
        "false_positive": false_positive,
        "false_negative": false_negative,
        "true_positive": true_positive,
    }


def build_segment_performance(scores: pd.DataFrame, threshold: float) -> pd.DataFrame:
    rows: list[dict[str, object]] = []

    for split_name, split_frame in scores.groupby("split", dropna=False):
        rows.append(
            {
                "scope": "all_splits",
                "dimension": "split",
                "segment": split_name,
                **_metrics_for_frame(split_frame, threshold),
            }
        )

    test = scores.loc[scores["split"] == "test"].copy()
    rows.append(
        {
            "scope": "test",
            "dimension": "overall",
            "segment": "test_all",
            **_metrics_for_frame(test, threshold),
        }
    )

    for dimension in ["fiscal_year", "market", "industry_macro_category"]:
        for segment, segment_frame in test.groupby(dimension, dropna=False):
            rows.append(
                {
                    "scope": "test",
                    "dimension": dimension,
                    "segment": segment,
                    **_metrics_for_frame(segment_frame, threshold),
                }
            )

    return pd.DataFrame(rows)


def _threshold_grid(scores: pd.DataFrame, primary_threshold: float) -> list[float]:
    candidates = {primary_threshold, DEFAULT_THRESHOLD}
    threshold_column = scores.get("threshold")
    if threshold_column is not None:
        for value in threshold_column.dropna().unique():
            numeric = _safe_float(value)
            if numeric is not None:
                candidates.add(numeric)
    candidates.update(np.round(np.arange(0.1, 0.91, 0.05), 4).tolist())
    return sorted(float(value) for value in candidates if 0.0 < float(value) < 1.0)


def build_threshold_sweep(scores: pd.DataFrame, primary_threshold: float) -> pd.DataFrame:
    test = scores.loc[scores["split"] == "test"].copy()
    rows = []
    for threshold in _threshold_grid(scores, primary_threshold):
        row = _metrics_for_frame(test, threshold)
        row["threshold"] = threshold
        rows.append(row)
    return pd.DataFrame(rows).sort_values("threshold").reset_index(drop=True)


def build_calibration_bins(scores: pd.DataFrame) -> pd.DataFrame:
    rows: list[pd.DataFrame] = []
    bins = np.linspace(0.0, 1.0, 11)
    for split in ["valid", "test"]:
        frame = scores.loc[scores["split"] == split].copy()
        frame["probability_bin"] = pd.cut(
            frame["prob_speculative"],
            bins=bins,
            include_lowest=True,
            right=True,
        )
        grouped = (
            frame.groupby("probability_bin", observed=False)
            .agg(
                rows=("stock_code", "size"),
                mean_probability=("prob_speculative", "mean"),
                actual_positive_rate=("is_speculative", "mean"),
            )
            .reset_index()
        )
        grouped["split"] = split
        grouped["probability_bin"] = grouped["probability_bin"].astype(str)
        grouped["calibration_gap"] = grouped["mean_probability"] - grouped["actual_positive_rate"]
        rows.append(grouped)
    return pd.concat(rows, ignore_index=True).loc[
        :,
        [
            "split",
            "probability_bin",
            "rows",
            "mean_probability",
            "actual_positive_rate",
            "calibration_gap",
        ],
    ]


def _label_from_value(value: int) -> str:
    return "투기등급" if int(value) == 1 else "투자적격"


def build_error_cases(
    scores: pd.DataFrame,
    threshold: float,
    *,
    top_error_cases: int,
) -> pd.DataFrame:
    test = scores.loc[scores["split"] == "test"].copy()
    test["predicted_label"] = (test["prob_speculative"] >= threshold).astype(int)
    test["decision_threshold"] = threshold
    test["probability_distance_from_threshold"] = (test["prob_speculative"] - threshold).abs()
    test["actual_label_name"] = test["is_speculative"].map(_label_from_value)
    test["predicted_label_name"] = test["predicted_label"].map(_label_from_value)

    false_positive = (
        test.loc[(test["is_speculative"] == 0) & (test["predicted_label"] == 1)]
        .sort_values("prob_speculative", ascending=False)
        .head(top_error_cases)
        .copy()
    )
    false_positive["error_type"] = "false_positive"
    false_positive["error_note"] = "모델은 부적격으로 봤지만 실제 라벨은 투자적격"

    false_negative = (
        test.loc[(test["is_speculative"] == 1) & (test["predicted_label"] == 0)]
        .sort_values("prob_speculative", ascending=True)
        .head(top_error_cases)
        .copy()
    )
    false_negative["error_type"] = "false_negative"
    false_negative["error_note"] = "모델은 투자적격으로 봤지만 실제 라벨은 투기등급"

    error_cases = pd.concat([false_positive, false_negative], ignore_index=True)
    keep_columns = [
        "error_type",
        "error_note",
        "corp_name",
        "stock_code",
        "market",
        "fiscal_year",
        "eval_year",
        "industry_macro_category",
        "prob_speculative",
        "decision_threshold",
        "actual_label_name",
        "predicted_label_name",
        "probability_distance_from_threshold",
    ]
    for column in keep_columns:
        if column not in error_cases.columns:
            error_cases[column] = pd.NA
    return error_cases.loc[:, keep_columns]


def _best_threshold_row(threshold_sweep: pd.DataFrame, metric: str) -> dict[str, Any]:
    frame = threshold_sweep.dropna(subset=[metric])
    if frame.empty:
        return {}
    row = frame.sort_values([metric, "threshold"], ascending=[False, True]).iloc[0]
    return {key: row[key] for key in frame.columns}


def _weakest_segments(segment_performance: pd.DataFrame, top_n: int = 5) -> list[dict[str, Any]]:
    test_segments = segment_performance.loc[
        (segment_performance["scope"] == "test")
        & (segment_performance["dimension"].isin(["market", "industry_macro_category"]))
        & (segment_performance["positive_rows"] > 0)
        & (segment_performance["rows"] >= 20)
    ].copy()
    if test_segments.empty:
        return []
    return (
        test_segments.sort_values(["f1", "rows"], ascending=[True, False])
        .head(top_n)
        .to_dict(orient="records")
    )


def _probability_calibration_summary_from_scores(scores: pd.DataFrame) -> dict[str, object]:
    if "prob_speculative_raw" not in scores.columns:
        return {"method": "none"}

    from sklearn.metrics import brier_score_loss, log_loss

    method = "unknown"
    if "probability_calibration_method" in scores.columns:
        methods = scores["probability_calibration_method"].dropna().astype(str).unique()
        if len(methods):
            method = methods[0]

    summary: dict[str, object] = {"method": method}
    for split in ["valid", "test"]:
        frame = scores.loc[scores["split"] == split].copy()
        if frame.empty or frame["is_speculative"].nunique() < 2:
            continue
        y_true = frame["is_speculative"].astype(int)
        raw = pd.to_numeric(frame["prob_speculative_raw"], errors="coerce").to_numpy(dtype=float)
        calibrated = pd.to_numeric(frame["prob_speculative"], errors="coerce").to_numpy(dtype=float)
        raw = np.clip(raw, 1e-6, 1 - 1e-6)
        calibrated = np.clip(calibrated, 1e-6, 1 - 1e-6)
        summary[split] = {
            "brier_raw": float(brier_score_loss(y_true, raw)),
            "brier_calibrated": float(brier_score_loss(y_true, calibrated)),
            "logloss_raw": float(log_loss(y_true, raw)),
            "logloss_calibrated": float(log_loss(y_true, calibrated)),
        }
    return summary


def build_summary_payload(
    *,
    scores: pd.DataFrame,
    threshold: float,
    segment_performance: pd.DataFrame,
    threshold_sweep: pd.DataFrame,
    calibration_bins: pd.DataFrame,
    error_cases: pd.DataFrame,
    prediction_scores_path: Path,
) -> dict[str, Any]:
    test = scores.loc[scores["split"] == "test"].copy()
    primary_metrics = _metrics_for_frame(test, threshold)
    tuned_thresholds = sorted(
        {
            float(value)
            for value in scores.get("threshold", pd.Series(dtype=float)).dropna().unique()
            if _safe_float(value) is not None
        }
    )

    calibration_summary = (
        calibration_bins.loc[calibration_bins["split"] == "test"]
        .assign(abs_gap=lambda frame: frame["calibration_gap"].abs())
        .sort_values("abs_gap", ascending=False)
        .head(3)
        .drop(columns=["abs_gap"])
        .to_dict(orient="records")
    )

    return {
        "generated_at_utc": datetime.now(UTC).isoformat(timespec="seconds"),
        "dataset_name": "credit_43_features",
        "model_name": "feature_43_xgboost",
        "prediction_scores_path": str(prediction_scores_path.relative_to(ROOT)),
        "primary_threshold": threshold,
        "available_tuned_thresholds": tuned_thresholds,
        "primary_test_metrics": primary_metrics,
        "probability_calibration": _probability_calibration_summary_from_scores(scores),
        "best_f1_threshold": _best_threshold_row(threshold_sweep, "f1"),
        "best_balanced_accuracy_threshold": _best_threshold_row(
            threshold_sweep,
            "balanced_accuracy",
        ),
        "weakest_test_segments": _weakest_segments(segment_performance),
        "largest_test_calibration_gaps": calibration_summary,
        "error_case_counts": error_cases["error_type"].value_counts().to_dict(),
    }


def _format_number(value: object, digits: int = 4) -> str:
    numeric = _safe_float(value)
    if numeric is None:
        return "-"
    return f"{numeric:.{digits}f}"


def _format_count(value: object) -> str:
    numeric = _safe_float(value)
    if numeric is None:
        return "-"
    return f"{int(numeric):,}"


def _markdown_table(
    rows: list[dict[str, object]],
    columns: list[tuple[str, str, str]],
) -> str:
    header = "| " + " | ".join(label for label, _, _ in columns) + " |"
    separator = "| " + " | ".join("---" for _ in columns) + " |"
    body = []
    for row in rows:
        values = []
        for _, key, kind in columns:
            value = row.get(key)
            if kind == "count":
                values.append(_format_count(value))
            elif kind == "metric":
                values.append(_format_number(value))
            elif kind == "percent":
                numeric = _safe_float(value)
                values.append("-" if numeric is None else f"{numeric * 100:.1f}%")
            else:
                values.append(str(value) if value is not None else "-")
        body.append("| " + " | ".join(values) + " |")
    return "\n".join([header, separator, *body])


def _records_for_dimension(
    segment_performance: pd.DataFrame, dimension: str
) -> list[dict[str, Any]]:
    return (
        segment_performance.loc[
            (segment_performance["scope"] == "test")
            & (segment_performance["dimension"] == dimension)
        ]
        .sort_values("segment")
        .to_dict(orient="records")
    )


def _top_error_records(
    error_cases: pd.DataFrame, error_type: str, top_n: int = 5
) -> list[dict[str, Any]]:
    return (
        error_cases.loc[error_cases["error_type"] == error_type]
        .head(top_n)
        .to_dict(orient="records")
    )


